#!/usr/bin/env python3
# OpenPocket Bass, Bluetooth audio: writes firmware/bt/bt_stubs_gen.c, the stand-ins for what JieLi's classic members
# (third_party/jieli-bt, plus the ../jieli-ble members listed in SHARED) reference and the A2DP sink image does not build:
# functions return 0 and count the call (BT_STUB), data is zeroed storage of the declared size. Names the firmware
# defines itself are left out: they come from compiling openpocket.c for this image with the host's clang (-emit-llvm)
# without this file. Needs llvm-dis / llvm-nm / clang (LLVM 18 here). Run after changing the members or the firmware's glue:
#   python3 tools/bt/gen_stubs.py
import os, re, subprocess, sys, glob
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
V = os.environ.get("LLVM_SUFFIX", "-18")
BT = os.path.join(R, "third_party/jieli-bt"); BLE = os.path.join(R, "third_party/jieli-ble")
files = sorted(glob.glob(f"{BT}/*/*.bc")) + [os.path.join(BLE, l.strip()) for l in open(f"{BT}/SHARED") if l.strip() and not l.startswith("#")]
# symbols the linker script defines (firmware/app.ld): the section tables
LDDEF = set("""a2dp_sink_media_codec_begin a2dp_sink_media_codec_end a2dp_source_media_codec_begin a2dp_source_media_codec_end
a2dp_sink_media_probe_begin a2dp_sink_media_probe_end a2dp_event_handler_begin a2dp_event_handler_end sdp_record_item_begin
sdp_record_item_end bt_sleep_begin bt_sleep_end acl_rx_pool acl_rx_pool_end acl_tx_pool acl_tx_pool_end""".split())
defs, undef, decl = set(), set(), {}
for f in files:
    for l in subprocess.run([f"llvm-nm{V}", f], capture_output=True, text=True).stdout.splitlines():
        p = l.split()
        if len(p) < 2: continue
        (undef if p[-2] == "U" else defs if p[-2] in "TDBRCVW" else set()).add(p[-1])
    ir = subprocess.run([f"llvm-dis{V}", f, "-o", "-"], capture_output=True, text=True).stdout
    for m in re.finditer(r"^@(\S+) = external (?:dso_local )?(?:local_unnamed_addr )?(global|constant) (.+?)(?:, align (\d+))?$", ir, re.M):
        decl[m.group(1)] = ("data", m.group(2), m.group(3), int(m.group(4) or 4))
    for m in re.finditer(r"^declare .*? @([\w.$]+)\(", ir, re.M):
        decl.setdefault(m.group(1), ("func",))
need = undef - defs - LDDEF
# the firmware's own definitions (this image, without the generated file)
fw = os.path.join(R, "firmware"); os.makedirs("/tmp/opbt", exist_ok=True); open("/tmp/opbt/channel.h", "w").close()
cmd = [f"clang{V}", "-target", "i386-unknown-elf", "-m32", "-ffreestanding", "-fno-builtin", "-w", "-c", "-emit-llvm",
       "-DPX_SR=44100.0f", "-DPX_OVERSAMPLE=4", "-DPX_BASS=1", "-DOP_BLE_TEST=1", "-DOP_BT_AUDIO=1", "-DBT_NO_GEN_STUBS=1", "-DOP_GUARD_STACK=0",
       f"-I{fw}/inc", f"-I{R}/engine", f"-I{fw}/ble", f"-I{fw}/bt", f"-I{fw}/bsp/chip", f"-I{fw}/bsp/boards/fm1", "-include", "/tmp/opbt/channel.h",
       f"{fw}/openpocket.c", "-o", "/tmp/opbt/op.bc"]
r = subprocess.run(cmd, capture_output=True, text=True)
if r.returncode: sys.exit(r.stderr[-3000:])
fwdef = set(l.split()[-1] for l in subprocess.run([f"llvm-nm{V}", "--defined-only", "/tmp/opbt/op.bc"], capture_output=True, text=True).stdout.splitlines() if l.split())
# names only the firmware's assembly or the other C files define (crt0, the RAM code, px_dsp.c)
fwdef |= set("memcpy memset".split())
need -= fwdef
def size(t):
    t = t.strip()
    m = re.match(r"i(\d+)$", t)
    if m: return max(1, int(m.group(1)) // 8)
    if t == "ptr": return 4
    m = re.match(r"\[(\d+) x (.+)\]$", t)
    if m: return int(m.group(1)) * size(m.group(2))
    return None
out = ["/* SPDX-License-Identifier: GPL-3.0-only OR MPL-2.0 */",
       "/* GENERATED by tools/bt/gen_stubs.py: do not edit. What JieLi's classic Bluetooth members reference and the A2DP sink",
       " * image does not build (LE, TWS, HFP, SPP, HID, PAN, test modes, Wi-Fi coexistence...). A function returns 0 and counts",
       " * the call (bt_stub_calls, bt_stub_last: a call that should not happen shows on the status line); data is zeroed. */",
       "#include <stdint.h>", "#include \"bt_stub.h\""]
fn, data, odd = [], [], []
for n in sorted(need):
    d = decl.get(n)
    if not d: odd.append(n); continue
    if d[0] == "func":
        if re.match(r"log_tag_const_", n): odd.append(n)
        else: fn.append(n)
    else:
        s = size(d[2])
        if s is None: s = 64; odd.append(f"{n} (type {d[2]}: 64 bytes)")
        data.append((n, s, d[1] == "constant", d[3]))
for n in fn: out.append(f"BT_STUB({n})")
for n, s, c, a in data:
    if n.startswith("log_tag_const_"): out.append(f"const char {n} = 0;"); continue
    out.append(f"{'const ' if c else ''}uint8_t {n}[{s}] __attribute__((aligned({max(a,1)})));" if s > 4 or not c else f"const uint{s*8 if s in (1,2,4) else 32}_t {n} = 0;")
open(os.path.join(fw, "bt/bt_stubs_gen.c"), "w").write("\n".join(out) + "\n")
# the image's C, with the file: it must compile (a redefinition shows here, not in CI)
r = subprocess.run([c for c in cmd if c != "-DBT_NO_GEN_STUBS=1" and c != "-w"] + ["-Wno-implicit-function-declaration"], capture_output=True, text=True)
errs = [l for l in r.stderr.splitlines() if "error" in l]
if r.returncode: sys.exit("\n".join(errs[:20]))
print(f"{len(files)} members, {len(undef)} undefined names, {len(fn)} function stubs, {len(data)} data; not classified: {odd}")
